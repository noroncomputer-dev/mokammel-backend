// تابع جستجوی پاسخ مناسب
const findResponse = (
  message: string,
): { response: string; suggestions: string[] } => {
  const lowerMessage = message.toLowerCase();

  // بررسی کلمات کلیدی
  for (const intent of intents) {
    for (const keyword of intent.keywords) {
      if (lowerMessage.includes(keyword.toLowerCase())) {
        return {
          response: intent.response,
          suggestions: intent.suggestions || [],
        };
      }
    }
  }

  // پاسخ پیش‌فرض
  return {
    response:
      "سوال شما در بانک اطلاعاتی ما موجود نیست. لطفاً سوال خود را دقیق‌تر مطرح کنید یا با پشتیبانی تماس بگیرید.\n\n📞 شماره پشتیبانی: ۰۲۱۱۲۳۴۵۶۷۸۹\n📧 ایمیل: support@mokammel.ir\n💬 واتساپ: ۰۹۱۲۳۴۵۶۷۸۹",
    suggestions: ["تماس با پشتیبانی", "محصولات محبوب", "سوال دیگر"],
  };
};

// ==================== ارسال پیام و دریافت پاسخ ====================
export const sendMessage = asyncHandler(
  async (req: AuthRequest, res: Response) => {
    const { message } = req.body;
    const sessionId = req.body.sessionId || `session_${Date.now()}`;
    const userId = req.user?._id;

    const { response, suggestions } = findResponse(message);

    // ذخیره در دیتابیس
    try {
      await ChatMessage.create({
        user: userId,
        message,
        response,
        sessionId,
      });
    } catch (error) {
      console.error("Error saving chat message:", error);
    }

    res.json(
      apiResponse(true, "پاسخ دریافت شد", {
        response,
        suggestions,
        sessionId,
      }),
    );
  },
);

// ==================== دریافت تاریخچه چت ====================
export const getChatHistory = asyncHandler(
  async (req: AuthRequest, res: Response) => {
    const { sessionId } = req.params;

    const history = await ChatMessage.find({ sessionId })
      .sort({ createdAt: 1 })
      .lean();

    res.json(apiResponse(true, "تاریخچه چت دریافت شد", { history }));
  },
);
